// The files the web build serves under /shared/, one per shared web specifier (ADR 0075). The import
// map in apps/web/index.html maps each specifier to its file, so a plugin's
// `import { useState } from 'react'` reaches the web build's own React. Each file reads the
// namespace that apps/web/src/plugins/host-shared.ts registers under Symbol.for('northmes.shared')
// and re-exports every name of it. An ES module exports names statically, so this script lists
// each package's names: the npm packages by importing them under node from apps/web, and
// @northmes/web-sdk by reading the value exports of its index.ts.

import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const repositoryRoot = fileURLToPath(new URL('..', import.meta.url));
const webDir = join(repositoryRoot, 'apps/web');

/** A name a module can export with `export const { name } = ...`. */
const identifier = /^[A-Za-z_$][\w$]*$/;

/**
 * The shared specifiers and the file of each under /shared/. Kept in step with HOST_PROVIDED_WEB
 * in @northmes/web-sdk, which gen.test.ts checks.
 */
export const sharedFiles = Object.freeze({
  react: 'react.js',
  'react-dom': 'react-dom.js',
  'react/jsx-runtime': 'react-jsx-runtime.js',
  '@tanstack/react-router': 'tanstack-react-router.js',
  '@apollo/client': 'apollo-client.js',
  '@apollo/client/react': 'apollo-client-react.js',
  '@northmes/web-sdk': 'northmes-web-sdk.js',
});

/** The export names of an npm package as node imports it from apps/web, without default. */
function npmExports(specifier) {
  const result = spawnSync(
    process.execPath,
    [
      '--input-type=module',
      '--eval',
      `console.log(JSON.stringify(Object.keys(await import(${JSON.stringify(specifier)}))))`,
    ],
    { cwd: webDir, encoding: 'utf8' },
  );
  if (result.status !== 0) throw new Error(`could not import ${specifier}:\n${result.stderr}`);
  return JSON.parse(result.stdout);
}

/** The value exports of @northmes/web-sdk, read from its index.ts: no type-only names. */
function webSdkExports() {
  const file = join(repositoryRoot, 'packages/web-sdk/src/index.ts');
  const source = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest);
  const names = [];
  for (const statement of source.statements) {
    if (!ts.isExportDeclaration(statement) || statement.isTypeOnly) continue;
    const clause = statement.exportClause;
    if (!clause || !ts.isNamedExports(clause)) {
      throw new Error('packages/web-sdk/src/index.ts may only use named re-exports');
    }
    for (const element of clause.elements) {
      if (!element.isTypeOnly) names.push(element.name.text);
    }
  }
  return names;
}

/** The text of the /shared/ file of `specifier`, which exports `names` and the default export. */
export function shimText(specifier, names) {
  const exported = [...new Set(names)].filter(
    (name) => name !== 'default' && identifier.test(name),
  );
  exported.sort();
  return [
    `// Generated by pnpm gen from the web build's ${specifier} (ADR 0075). Do not edit.`,
    `const shared = globalThis[Symbol.for('northmes.shared')][${JSON.stringify(specifier)}];`,
    'export default shared.default ?? shared;',
    `export const {\n${exported.map((name) => `  ${name},`).join('\n')}\n} = shared;`,
    '',
  ].join('\n');
}

/** Every file under apps/web/public/shared/, as paths relative to the repository root and texts. */
export function sharedShims() {
  return Object.entries(sharedFiles).map(([specifier, file]) => ({
    path: `apps/web/public/shared/${file}`,
    content: shimText(
      specifier,
      specifier === '@northmes/web-sdk' ? webSdkExports() : npmExports(specifier),
    ),
  }));
}

import { HOST_PROVIDED_WEB } from '@northmes/web-sdk/host-provided-web';
import { describe, expect, it } from 'vitest';
import { sharedFiles, sharedShims, shimText } from './shared-web.mjs';

describe('the shared web files', () => {
  it('ADR 0075 there is one /shared/ file per shared web specifier', () => {
    expect(Object.keys(sharedFiles)).toEqual([...HOST_PROVIDED_WEB]);
  });

  it('ADR 0075 a file reads its namespace from the registered object and re-exports each name and the default', () => {
    expect(shimText('react', ['useState', 'default', 'Children', 'not-a-name'])).toBe(
      [
        "// Generated by pnpm gen from the web build's react (ADR 0075). Do not edit.",
        'const shared = globalThis[Symbol.for(\'northmes.shared\')]["react"];',
        'export default shared.default ?? shared;',
        'export const {',
        '  Children,',
        '  useState,',
        '} = shared;',
        '',
      ].join('\n'),
    );
  });

  it("ADR 0075 the files export the packages' value names: React's hooks, the router's createRoute and the SDK's defineWebModule but not its types", () => {
    const shims = Object.fromEntries(sharedShims().map(({ path, content }) => [path, content]));

    expect(Object.keys(shims)).toEqual(
      Object.values(sharedFiles).map((file) => `apps/web/public/shared/${file}`),
    );
    expect(shims['apps/web/public/shared/react.js']).toContain('  useState,\n');
    expect(shims['apps/web/public/shared/react-jsx-runtime.js']).toContain('  jsxs,\n');
    expect(shims['apps/web/public/shared/tanstack-react-router.js']).toContain('  createRoute,\n');
    expect(shims['apps/web/public/shared/apollo-client-react.js']).toContain('  useQuery,\n');
    const sdk = shims['apps/web/public/shared/northmes-web-sdk.js'];
    expect(sdk).toContain('  defineWebModule,\n');
    expect(sdk).not.toContain('  WebModule,\n');
  });
});
